#!/usr/bin/env python3
"""The SH7604 model's decode (decode.txt, dump.sv) per the port's instruction kinds (sh2_ops.h): for each kind, the
registers its first state reads, whether its last state accesses memory and the register a read there loads, and
whether it is a bra/bsr with a 12-bit displacement; registers as the n field, the m field or a fixed number.
Prints a C++ table (machine/sh2_pipeline.h), or the kinds that are not the same for all their opcodes."""
import re, sys
ops_h = open(sys.argv[1]).read()
names = re.search(r"enum class Op : uint8_t \{(.*?)\};", ops_h, re.S).group(1).replace("\n", " ").split(",")
names = [n.strip() for n in names if n.strip()]
pats = re.findall(r"\{Op::(\w+), 0x([0-9A-F]+), 0x([0-9A-F]+)\}", ops_h)
def kind(op):
    for name, mask, match in pats:
        if op & int(mask, 16) == int(match, 16):
            return name
    return "Illegal"
rows = {}
for line in open(sys.argv[2]):
    f = line.split()
    op, st = int(f[0], 16), int(f[1])
    rows.setdefault(op, {})[st] = list(map(int, f[2:]))
# field indexes: 0 RA.N 1 RA.R 2 RA.W 3 RB.N 4 RB.R 5 RB.W 6 R0R 7 MEM.R 8 MEM.W 9 MAC.R 10 MAC.W 11 LST 12 BI 13 BT 14 IMMT 15 ILI 16 BD
def sym(reg, op):
    n, m = (op >> 8) & 15, (op >> 4) & 15
    out = set()
    if reg == n: out.add("n")
    if reg == m: out.add("m")
    out.add(str(reg))
    return out
info = {}
for op in range(65536):
    k = kind(op)
    st = rows[op]
    first, last = st[0], st[max(st)]
    reads = []
    if first[1]: reads.append(sym(first[0], op))
    if first[4]: reads.append(sym(first[3], op))
    if first[6]: reads.append({"0"})
    mem = 1 if (last[7] or last[8] or last[9] or last[10]) else 0
    load = sym(last[0], op) if ((last[7] or (last[9] and not last[8])) and last[2]) else {"none"}
    bra12 = 1 if (first[12] and first[13] == 2 and first[14] == 3) else 0
    info.setdefault(k, []).append((reads, mem, load, bra12))
bad = []
table = {}
for k in names:
    if k not in info:
        continue
    ent = info[k]
    nreads = {len(e[0]) for e in ent}
    mems = {e[1] for e in ent}
    bras = {e[3] for e in ent}
    if len(nreads) != 1 or len(mems) != 1 or len(bras) != 1:
        bad.append((k, nreads, mems, bras)); continue
    rs = []
    for i in range(nreads.pop()):
        common = set.intersection(*[e[0][i] for e in ent])
        if not common: bad.append((k, "read", i)); break
        rs.append(sorted(common, key=lambda x: (x not in ("n", "m"), x))[0])
    loadc = set.intersection(*[e[2] for e in ent])
    if not loadc: bad.append((k, "load")); continue
    load = sorted(loadc, key=lambda x: (x not in ("n", "m", "none"), x))[0]
    table[k] = (rs, mems.pop(), load, bras.pop())
if bad:
    print("not the same for all their opcodes:", bad, file=sys.stderr)
def reg(r):
    return {"n": "kRn", "m": "kRm", "none": "kNone"}.get(r, r)
print("// Generated by the timing harness's decode/kinds.py from jtcores' SH7604 model's decoder (SH_pkg.sv, GPL-3.0-or-later):")
print("// per kind of instruction, what its pipeline stalls depend on (machine/sh2_pipeline.h)")
for k in names:
    if k in table:
        rs, mem, load, bra = table[k]
        rr = (rs + ["kNone", "kNone", "kNone"])[:3]
        print("    {Op::%s, {%s}, %d, %s, %d}," % (k, ", ".join(reg(r) for r in rr), mem, reg(load), bra))
